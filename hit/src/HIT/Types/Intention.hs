module HIT.Types.Intention
  ( Origin (..),
    Source (..),
    Intention (..),
    SomeIntention (..),
    isDone,
    recordProgress,
  )
where

import Control.Applicative ((<|>))
import Data.Kind (Type)
import Data.List.NonEmpty (NonEmpty)
import Data.Text (Text)
import Data.Time (TimeOfDay, UTCTime)
import Data.Type.Equality (TestEquality (..), (:~:) (..))
import HIT.Types.Identifier (GoalIdentifier, HabitIdentifier, IntentionIdentifier, Username)
import HIT.Types.Interval (Interval)
import HIT.Types.Refined (Progress, Target, Title, unrefine)
import HIT.Types.Schedule (Window)
import Prelude hiding (id)

-- | an origin is where an intention comes from, promoted to index intentions
data Origin
  = -- | planned for a day by the user
    OneOff
  | -- | generated by a habit
    Recurring

-- | a source is the origin of an intention, with the habit when recurring
type Source :: Origin -> Type
data Source origin where
  -- | planned by the user
  OneOffSource :: Source 'OneOff
  -- | an occurrence of this habit
  RecurringSource :: HabitIdentifier -> Source 'Recurring

deriving stock instance Show (Source origin)

deriving stock instance Eq (Source origin)

instance TestEquality Source where
  testEquality OneOffSource OneOffSource = Just Refl
  testEquality (RecurringSource _) (RecurringSource _) = Just Refl
  testEquality _ _ = Nothing

-- | an intention is a task that's due in its window, and marked as done when its progress reaches target
type Intention :: Origin -> Interval -> Type
data Intention origin interval = Intention
  { -- | primary key
    id :: IntentionIdentifier,
    -- | owner
    owner :: Username,
    -- | where it comes from, fixing the origin
    source :: Source origin,
    -- | what to do
    title :: Title,
    -- | amount to reach, 1 for a plain check-off
    target :: Target,
    -- | unit of target and progress, e.g. words, nothing for a count
    unit :: Maybe Text,
    -- | amount done so far, change only through 'recordProgress'
    progress :: Progress,
    -- | days it is due on, fixing the interval
    window :: Window interval,
    -- | local time it is due by on the last day of its window
    dueTime :: Maybe TimeOfDay,
    -- | when progress last reached target, nothing iff not done
    doneAt :: Maybe UTCTime,
    -- | goals it serves
    goals :: NonEmpty GoalIdentifier,
    -- | creation time
    createdAt :: UTCTime,
    -- | last update, at least createdAt
    modifiedAt :: UTCTime
  }

deriving stock instance Show (Intention origin interval)

deriving stock instance Eq (Intention origin interval)

-- | some intention is an intention of any origin and interval, as listed or decoded
data SomeIntention where
  SomeIntention :: Intention origin interval -> SomeIntention

deriving stock instance Show SomeIntention

-- | equal iff the origins and intervals match and the intentions are equal
instance Eq SomeIntention where
  SomeIntention a == SomeIntention b = case (testEquality a.source b.source, testEquality a.window b.window) of
    (Just Refl, Just Refl) -> a == b
    _ -> False

-- | done iff progress reaches target
isDone :: Intention origin interval -> Bool
isDone i = unrefine i.progress >= unrefine i.target

-- | set progress at a time, keeping doneAt nothing iff not done, and the first time done otherwise
recordProgress :: UTCTime -> Progress -> Intention origin interval -> Intention origin interval
recordProgress now p i =
  let i' = i {progress = p}
   in i' {doneAt = if isDone i' then i.doneAt <|> Just now else Nothing}
